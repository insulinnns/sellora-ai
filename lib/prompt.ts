import type { GenerateRequestInput } from "./schema";

/**
 * Системная инструкция для Gemini: роль, правила и формат ответа.
 * Отделена от пользовательских данных, чтобы модель не путала
 * инструкции с содержимым, которое ввёл пользователь.
 */
export function buildSystemInstruction(): string {
  return `Ты — профессиональный e-commerce copywriter, который пишет карточки товаров для маркетплейсов.

Правила:
- Пиши только на русском языке.
- Используй только ту информацию о товаре, которую предоставил пользователь.
- Никогда не придумывай: характеристики, сертификаты, гарантии, скидки, цены, результаты использования, медицинские свойства, официальные заявления бренда.
- Если пользователь не указал конкретную характеристику, не утверждай её как факт и не додумывай её.
- Стиль текста должен точно соответствовать выбранному пользователем тону и длине.
- Результат должен быть конкретным, естественным и готовым к публикации на маркетплейсе.
- SEO-ключевые слова должны быть релевантны именно этому товару, без бессмысленного наполнения ключевиками.
- Верни ОДИН валидный JSON-объект и ничего кроме него: без markdown-разметки, без пояснений, без code fence.

Формат ответа (строго):
{
  "titles": ["вариант 1", "вариант 2", "вариант 3"],
  "shortDescription": "краткое описание товара, 1-2 предложения",
  "description": "продающее описание товара, несколько абзацев",
  "benefits": ["преимущество 1", "преимущество 2", "..."],
  "seoKeywords": ["ключ 1", "ключ 2", "..."],
  "marketingText": "короткий рекламный текст для объявления или соцсетей"
}

В "benefits" должно быть от 4 до 6 пунктов, если это позволяет объём информации от пользователя.`;
}

/**
 * Пользовательская часть промпта — структурированные данные о товаре.
 */
export function buildUserPrompt(input: GenerateRequestInput): string {
  const parts: string[] = [
    `Название товара: ${input.productName}`,
    `Категория: ${input.category}`,
    `Характеристики: ${input.features}`,
    `Целевая аудитория: ${input.audience}`,
    `Тон текста: ${input.tone}`,
    `Желаемая длина текста: ${input.length}`,
  ];

  if (input.additionalInstructions && input.additionalInstructions.trim()) {
    parts.push(`Дополнительные пожелания: ${input.additionalInstructions.trim()}`);
  }

  if (input.avoidUnverifiedClaims) {
    parts.push(
      "Важно: не используй ни одной характеристики, сертификата, гарантии или свойства, которые не были явно перечислены выше."
    );
  }

  if (input.image) {
    parts.push(
      "К запросу приложено изображение товара — используй его только как дополнительный визуальный контекст (форма, цвет, стиль), не утверждай на его основе технические характеристики, которых нет в тексте."
    );
  }

  return parts.join("\n");
}
